import { chromium } from '@playwright/test'
const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] })
const p = await b.newPage()
p.on('response', r => { if (r.url().includes('/api/')) console.log('api:', r.status(), r.url().slice(0, 80)) })
p.on('pageerror', e => console.log('PAGEERR:', String(e).slice(0, 150)))
await p.goto('http://localhost:3000/')
await p.fill('input[type="email"]', 'admin@axiom.mx')
await p.fill('input[type="password"]', 'axiom12345')
await p.click('button[type="submit"]')
await p.waitForTimeout(6000)
const hello = await p.locator('.axiom-hello').count()
const err = await p.locator('text=/intent|bloquead|error|incorrect/i').count()
console.log('hello:', hello, '| mensajes de error:', err)
const body = await p.locator('body').innerText()
console.log(body.slice(0, 400))
await b.close()
